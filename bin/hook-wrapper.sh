#!/bin/sh
# hook-wrapper.sh - POSIX-compatible wrapper for lazy binary download
# Checks if binary exists AND version matches, downloads if needed, runs hook
#
# This wrapper enables auto-download of binaries after plugin auto-update.
# Claude Code plugins don't have post-install hooks, so we use lazy loading.
#
# RELIABILITY: All operations use || true to never block Claude.

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PLUGIN_JSON="$SCRIPT_DIR/../.claude-plugin/plugin.json"
INSTALL_SCRIPT="$SCRIPT_DIR/install.sh"


# On Windows prefer the native .exe (reliable from sh). Keep .bat for users who run it from cmd.exe.
detect_windows_binary() {
    # Allow overriding for debugging/custom installs
    if [ -n "${CLAUDE_NOTIFICATIONS_BIN:-}" ] && [ -f "$CLAUDE_NOTIFICATIONS_BIN" ]; then
        BINARY="$CLAUDE_NOTIFICATIONS_BIN"
        return 0
    fi

    # Prefer the downloaded Windows executable (supports argv reliably)
    arch_raw="$(uname -m 2>/dev/null || true)"
    arch=""
    case "$arch_raw" in
        x86_64|amd64) arch="amd64" ;;
        arm64|aarch64) arch="arm64" ;;
        *) arch="" ;;
    esac

    if [ -n "$arch" ] && [ -f "$SCRIPT_DIR/claude-notifications-windows-$arch.exe" ]; then
        BINARY="$SCRIPT_DIR/claude-notifications-windows-$arch.exe"
        return 0
    fi

    # Fallback: any Windows executable present
    for exe in "$SCRIPT_DIR"/claude-notifications-windows-*.exe; do
        if [ -f "$exe" ]; then
            BINARY="$exe"
            return 0
        fi
    done

    # Fallback: legacy wrapper generated by install.sh
    BINARY="$SCRIPT_DIR/claude-notifications.bat"
    return 0
}

run_windows_bat() {
    # Best-effort: run .bat via cmd.exe (Git Bash/MSYS/Cygwin)
    if command -v cmd.exe >/dev/null 2>&1; then
        WIN_BIN="$BINARY"
        if command -v cygpath >/dev/null 2>&1; then
            WIN_BIN="$(cygpath -w "$BINARY" 2>/dev/null || printf '%s' "$BINARY")"
        fi
        # Let the runtime build a command line from argv (handles spaces reasonably well).
        # NOTE: Avoid manual quoting/escaping here; MSYS/Cygwin handle argv → Windows command line conversion.
        cmd.exe /d /s /c call "$WIN_BIN" "$@"
        return $?
    fi

    # Last resort (may fail under sh)
    "$BINARY" "$@"
}

run_binary() {
    if [ "$IS_WINDOWS" = 1 ]; then
        case "$BINARY" in
            *.bat|*.cmd) run_windows_bat "$@" ;;
            *)           "$BINARY" "$@" ;;
        esac
    else
        "$BINARY" "$@"
    fi
}

# Platform detection
# Primary: uname -s (Git Bash, MSYS2, Cygwin)
# Fallback: $OS env var (set to "Windows_NT" on ALL Windows systems, even non-MSYS shells)
IS_WINDOWS=0
case "$(uname -s)" in
    MINGW*|MSYS*|CYGWIN*) IS_WINDOWS=1 ;;
esac
if [ "$IS_WINDOWS" = 0 ]; then
    case "${OS:-}" in
        Windows*) IS_WINDOWS=1 ;;
    esac
fi

if [ "$IS_WINDOWS" = 1 ]; then
    detect_windows_binary
else
    BINARY="$SCRIPT_DIR/claude-notifications"
fi

# Guard: if BINARY is a Git text-symlink stub (not a real symlink), resolve or invalidate it.
# Git on Windows (core.symlinks=false) creates plain text files instead of symlinks.
# Content is just the target name, e.g. "claude-notifications-darwin-arm64".
if [ -f "$BINARY" ] && [ ! -L "$BINARY" ]; then
    # Text stubs are tiny (<1KB). Skip real binaries (MB-sized) to avoid false positives.
    _size=$(wc -c < "$BINARY" 2>/dev/null || echo 999999)
    if [ "$_size" -lt 1024 ]; then
        # Read first 256 bytes max (avoid reading huge files if size check is bypassed)
        _first_line=$(head -c 256 "$BINARY" 2>/dev/null | head -n 1 | tr -d '[:space:]')
        case "$_first_line" in
            claude-notifications-darwin-*|claude-notifications-linux-*|claude-notifications-windows-*)
                # Text stub detected — resolve to actual target if it exists
                if [ -x "$SCRIPT_DIR/$_first_line" ]; then
                    BINARY="$SCRIPT_DIR/$_first_line"
                else
                    # Target doesn't exist (wrong platform) — force re-install
                    BINARY="$SCRIPT_DIR/claude-notifications-MISSING"
                fi
                ;;
        esac
    fi
fi

# Check if binary is ready (exists and executable on Unix, exists on Windows)
binary_ok() {
    if [ "$IS_WINDOWS" = 1 ]; then
        [ -f "$BINARY" ]
    else
        [ -x "$BINARY" ]
    fi
}

# Get version from binary or plugin.json (returns empty on failure)
get_binary_version() {
    run_binary version 2>/dev/null | grep -Eo '[0-9]+\.[0-9]+\.[0-9]+' | head -n 1 || true
}

get_plugin_version() {
    [ -f "$PLUGIN_JSON" ] && grep -Eo '[0-9]+\.[0-9]+\.[0-9]+' "$PLUGIN_JSON" | head -n 1 || true
}

# Run install.sh silently. The caller reports a safe, once-per-version failure.
run_install() {
    [ -f "$INSTALL_SCRIPT" ] || return 1
    # A package rollback must not delegate mutation to a historical writer.
    # This compatibility declaration does not authenticate the package origin.
    LC_ALL=C grep -aqF 'agent-notifications-managed-writer-protocol-v1' "$INSTALL_SCRIPT" || return 1
    INSTALL_TARGET_DIR="$SCRIPT_DIR" "$INSTALL_SCRIPT" "$@" >/dev/null 2>&1
}

report_install_failure() {
    # Codex observation hooks must leave both output streams empty.
    [ "${CN_PRODUCT:-claude}" = "claude" ] || return 0
    _failed_ver=$(get_plugin_version)
    [ -n "$_failed_ver" ] || _failed_ver=unknown
    _failure_stamp="$STAMP_DIR/install-failed-$_failed_ver"
    mkdir -p "$STAMP_DIR" >/dev/null 2>&1 || true
    # mkdir is atomic across concurrent hooks. If cache writes fail, still
    # report the failure rather than hiding a missing runtime indefinitely.
    if mkdir "$_failure_stamp" 2>/dev/null || [ ! -d "$_failure_stamp" ]; then
        if ! binary_ok; then
            printf '{"systemMessage":"[claude-notifications] Installation of v%s failed. Run bin/install.sh manually for details."}\n' "$_failed_ver"
        else
            printf '[claude-notifications] Installation of v%s failed. Run bin/install.sh manually for details.\n' "$_failed_ver" >&2
        fi
    fi
}

install_in_progress() {
    _lock="$SCRIPT_DIR/.install.lock"
    [ -d "$_lock" ] && [ ! -L "$_lock" ] || return 1
    _owner=""
    for _entry in "$_lock"/* "$_lock"/.[!.]* "$_lock"/..?*; do
        [ -e "$_entry" ] || [ -L "$_entry" ] || continue
        case "$_entry" in
            "$_lock"/.owner.*)
                [ -d "$_entry" ] && [ ! -L "$_entry" ] && [ -z "$_owner" ] || return 1
                _owner="$_entry"
                ;;
            *) return 1 ;;
        esac
    done
    [ -n "$_owner" ] || return 1
    _metadata_count=0
    for _entry in "$_owner"/* "$_owner"/.[!.]* "$_owner"/..?*; do
        [ -e "$_entry" ] || [ -L "$_entry" ] || continue
        case "$_entry" in
            "$_owner/pid"|"$_owner/heartbeat")
                [ -f "$_entry" ] && [ ! -L "$_entry" ] || return 1
                _metadata_count=$((_metadata_count + 1))
                ;;
            *) return 1 ;;
        esac
    done
    [ "$_metadata_count" = 2 ] || return 1
    IFS= read -r _owner_pid < "$_owner/pid" || return 1
    case "$_owner_pid" in ''|*[!0-9]*) return 1 ;; esac
    kill -0 "$_owner_pid" 2>/dev/null
}

wait_for_install_publication() {
    _wait_attempt=0
    while [ "$_wait_attempt" -lt 2 ]; do
        binary_ok && return 0
        install_in_progress && return 0
        [ -d "$SCRIPT_DIR/.install.lock" ] && [ ! -L "$SCRIPT_DIR/.install.lock" ] || return 1
        sleep 1
        _wait_attempt=$((_wait_attempt + 1))
    done
    binary_ok || install_in_progress
}

# === Main Logic ===

STAMP_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/claude-notifications-go"
# Keep every Codex stamp write out of the legacy Claude cache.
if [ "${CN_PRODUCT:-claude}" = "codex" ]; then
    STAMP_DIR="$STAMP_DIR/codex"
fi
VERSION_CACHE="$STAMP_DIR/verified-version"

NEED_INSTALL=0
NEED_FORCE=0

if ! binary_ok; then
    # Binary missing - need install
    NEED_INSTALL=1
else
    # Binary exists - check version using cache to skip slow binary launch (~150ms)
    PLG_VER=$(get_plugin_version)

    # Version cache: if plugin.json version matches cached version, skip get_binary_version
    CACHED_VER=""
    [ -f "$VERSION_CACHE" ] && IFS= read -r CACHED_VER < "$VERSION_CACHE" 2>/dev/null

    # The version cache is shared across plugin roots (keyed by version only),
    # so the Codex route always queries the real binary: a cache hit earned by
    # the Claude root must not let the old-binary guard trust a stale binary
    # sitting in the Codex root.
    if [ "${CN_PRODUCT:-claude}" = "claude" ] && [ -n "$PLG_VER" ] && [ "$CACHED_VER" = "$PLG_VER" ]; then
        # Cache hit — skip binary version check
        BIN_VER="$PLG_VER"
    else
        # Cache miss — run binary to get actual version
        BIN_VER=$(get_binary_version)
    fi

    # Update only if both versions are known and differ
    if [ -n "$BIN_VER" ] && [ -n "$PLG_VER" ] && [ "$BIN_VER" != "$PLG_VER" ]; then
        NEED_INSTALL=1
        NEED_FORCE=1
    elif [ -n "$BIN_VER" ] && [ -n "$PLG_VER" ] && [ "$CACHED_VER" != "$PLG_VER" ]; then
        # Versions match but cache is stale — update cache
        mkdir -p "$STAMP_DIR" >/dev/null 2>&1 || true
        printf '%s\n' "$PLG_VER" > "$VERSION_CACHE" 2>/dev/null || true
    fi
fi

# Install if needed and notify user
if [ "$NEED_INSTALL" = 1 ]; then
    INSTALL_FAILED=0
    if [ "$NEED_FORCE" = 1 ]; then
        run_install --force || INSTALL_FAILED=1
    else
        run_install || INSTALL_FAILED=1
    fi

    # On Windows, re-detect binary after install to prefer .exe over .bat
    if [ "$IS_WINDOWS" = 1 ]; then
        detect_windows_binary
    fi

    if binary_ok; then
        NEW_VER=$(get_binary_version)
        # Update version cache after successful install
        if [ -n "$NEW_VER" ]; then
            mkdir -p "$STAMP_DIR" >/dev/null 2>&1 || true
            printf '%s\n' "$NEW_VER" > "$VERSION_CACHE" 2>/dev/null || true
        fi
        # Avoid repeating the same install/update message more than once per version.
        if [ -n "$NEW_VER" ]; then
            STAMP_FILE="$STAMP_DIR/update-stamp"
            mkdir -p "$STAMP_DIR" >/dev/null 2>&1 || true

            STAMP_KEY="$NEW_VER:$NEED_FORCE"
            PREV_KEY=""
            if [ -f "$STAMP_FILE" ]; then
                IFS= read -r PREV_KEY < "$STAMP_FILE" 2>/dev/null || true
            fi

            if [ "$PREV_KEY" != "$STAMP_KEY" ]; then
                printf '%s\n' "$STAMP_KEY" > "$STAMP_FILE" 2>/dev/null || true
                # Disabled: the system message was shown too frequently despite the stamp file.
                # if [ "$NEED_FORCE" = 1 ]; then
                #     printf '{"systemMessage":"[claude-notifications] Updated to v%s"}\n' "$NEW_VER"
                # else
                #     printf '{"systemMessage":"[claude-notifications] Installed v%s"}\n' "$NEW_VER"
                # fi
            fi
        fi
    fi
    if [ "$INSTALL_FAILED" = 1 ] || ! binary_ok; then
        # Keep update/preflight failures silent while a usable old binary is
        # retained. Only a verified live installer suppresses the diagnostic.
        if ! binary_ok && ! wait_for_install_publication; then
            report_install_failure
        fi
    fi
fi

# Compare dotted numeric versions: succeeds when $1 >= $2.
version_ge() {
    [ -n "$1" ] && [ -n "$2" ] || return 1
    _a1=$(printf '%s' "$1" | cut -d. -f1); _a2=$(printf '%s' "$1" | cut -d. -f2); _a3=$(printf '%s' "$1" | cut -d. -f3)
    _b1=$(printf '%s' "$2" | cut -d. -f1); _b2=$(printf '%s' "$2" | cut -d. -f2); _b3=$(printf '%s' "$2" | cut -d. -f3)
    _a1=${_a1:-0}; _a2=${_a2:-0}; _a3=${_a3:-0}; _b1=${_b1:-0}; _b2=${_b2:-0}; _b3=${_b3:-0}
    case "$_a1$_a2$_a3$_b1$_b2$_b3" in *[!0-9]*) return 1 ;; esac
    [ "$_a1" -gt "$_b1" ] && return 0
    [ "$_a1" -lt "$_b1" ] && return 1
    [ "$_a2" -gt "$_b2" ] && return 0
    [ "$_a2" -lt "$_b2" ] && return 1
    [ "$_a3" -ge "$_b3" ]
}

# Run hook or exit gracefully
if binary_ok; then
    # Export plugin root so the binary can find ClaudeNotifier.app and other resources
    if [ -z "$CLAUDE_PLUGIN_ROOT" ]; then
        CLAUDE_PLUGIN_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
    fi
    export CLAUDE_PLUGIN_ROOT

    # Claude-only side effects. The Codex route (CN_PRODUCT=codex, set by
    # bin/codex-hook-wrapper.sh) must never write under ~/.claude: alternating
    # Claude/Codex plugin caches would ping-pong the pointer file and corrupt
    # the fallback consumed by old-version shims (bin/bootstrap.sh).
    if [ "${CN_PRODUCT:-claude}" = "claude" ]; then
        # Persist a stable pointer to the current plugin root outside the plugin cache.
        # This is a best-effort fallback for older cached paths and for shim wrappers.
        _CLAUDE_HOME="${CLAUDE_CONFIG_DIR:-${CLAUDE_HOME:-$HOME/.claude}}"
        if [ -z "$_CLAUDE_HOME" ]; then
            _CLAUDE_HOME="$HOME/.claude"
        fi
        _PTR_DIR="$_CLAUDE_HOME/claude-notifications-go"
        _PTR_FILE="$_PTR_DIR/plugin-root"
        mkdir -p "$_PTR_DIR" >/dev/null 2>&1 || true
        _PREV_PTR=""
        if [ -f "$_PTR_FILE" ]; then
            IFS= read -r _PREV_PTR < "$_PTR_FILE" 2>/dev/null || true
        fi
        if [ "$_PREV_PTR" != "$CLAUDE_PLUGIN_ROOT" ]; then
            _TMP_PTR="$_PTR_FILE.tmp.$$"
            printf '%s\n' "$CLAUDE_PLUGIN_ROOT" > "$_TMP_PTR" 2>/dev/null && \
                mv "$_TMP_PTR" "$_PTR_FILE" 2>/dev/null || true
            rm -f "$_TMP_PTR" 2>/dev/null || true
        fi
    fi

    # Codex route guard: binaries older than the first Codex-capable release
    # dispatch handle-hook on the event name alone and silently ignore
    # "--product codex", which would misroute the Codex payload into the
    # Claude decoder. If the install above could not produce a new-enough
    # binary, exit silently instead of running the wrong route.
    if [ "${CN_PRODUCT:-claude}" = "codex" ] && [ -n "${CN_CODEX_MIN_VERSION:-}" ]; then
        _CODEX_BIN_VER="${NEW_VER:-${BIN_VER:-}}"
        if [ -z "$_CODEX_BIN_VER" ]; then
            _CODEX_BIN_VER=$(get_binary_version)
        fi
        if ! version_ge "$_CODEX_BIN_VER" "$CN_CODEX_MIN_VERSION"; then
            exit 0
        fi
    fi

    run_binary "$@" || true
fi

exit 0
