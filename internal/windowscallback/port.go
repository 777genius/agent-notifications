var ErrUnavailable = errors.New("windows callback installed qualification unavailable")

type Outcome string

const (
	Unavailable Outcome = "unavailable"
	Declined    Outcome = "declined"
	Accepted    Outcome = "accepted"
	Unknown     Outcome = "unknown"
)

// Result does not expose HRESULT or claim focus/render or an exact FullName lock.
type Result struct {
	Outcome         Outcome
	EffectEntered   bool
	TargetConfirmed bool
}
type Binding struct{ SnapshotPath, SHA256 string }

// Binding is an immutable transport value. Exact names reject case-folded or
// invented aliases that typed JSON would otherwise silently map or ignore.
func (b *Binding) UnmarshalJSON(data []byte) error {
	if strictjson.Validate(data, strictjson.Budget{Bytes: 64 * 1024, Depth: 4, Entries: 16}) != nil {
		return ErrEnvelope
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil || len(fields) != 2 {
		return ErrEnvelope
	}
	if _, ok := fields["SnapshotPath"]; !ok {
		return ErrEnvelope
	}
	if _, ok := fields["SHA256"]; !ok {
		return ErrEnvelope
	}
	var value struct {
		SnapshotPath string
		SHA256       string
	}
	if err := json.Unmarshal(data, &value); err != nil {
		return ErrEnvelope
	}
	*b = Binding{SnapshotPath: value.SnapshotPath, SHA256: value.SHA256}
	return nil
}

type NativePort interface {
	CheckReadiness(context.Context, Binding, uint64) error
}

// Port captures trusted static bytes. Only an explicit immutable binding may
// request installed readiness; construction performs no native probes.
type Port struct{ asset helperAsset }
type helperAsset struct {
	bytes  []byte
	digest string
}

// NewPort captures release bytes without inspecting them or any installed state.
// The Windows session retains this value as the future explicit setup seam.
func NewPort() Port { return Port{asset: helperAsset{helperBytes, helperDigest}} }

// TrustedAsset validates the captured immutable bytes only when explicit setup
// asks for extraction or explicit bound custody. Construction never validates it.
func (p Port) TrustedAsset() ([]byte, string, error) { return trustedAsset(p.asset) }

// TrustedAsset is a defensive copy of bytes generated by the release build.
// No caller-supplied hash, PATH lookup or runtime download can supply provenance.
func TrustedAsset() ([]byte, string, error) { return NewPort().TrustedAsset() }
func trustedAsset(asset helperAsset) ([]byte, string, error) {
	if len(asset.bytes) == 0 || len(asset.digest) != 64 {
		return nil, "", ErrUnavailable
	}
	d := sha256.Sum256(asset.bytes)
	if hex.EncodeToString(d[:]) != asset.digest {
		return nil, "", ErrUnavailable
	}
	return append([]byte(nil), asset.bytes...), asset.digest, nil
}

// ValidBinding validates the Windows lexical wire grammar on every host. Actual
// filesystem custody remains an independent Win32 observation.
func ValidBinding(b Binding) bool {
	_, validPath := bindingPath(b.SnapshotPath)
	return hexValue(b.SHA256, 64) && validPath
}
